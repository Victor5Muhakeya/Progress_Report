    function renderListPage(view, config) {
        const action = config.add ? `<button class="button button-primary" data-action="add" data-type="${esc(config.type)}">＋ ${esc(config.addLabel || "Add record")}</button>` : "";
        content.innerHTML = `${heading(view, action)}${toolbar(config.searchPlaceholder || "Search records", config.filters || [])}<div class="table-card" id="dataTable"></div>`;
        currentFilters = {};
        const search = content.querySelector("[data-search]");
        const table = content.querySelector("#dataTable");
        let page = 0;
        const pageSize = 10;
        const draw = () => {
            let rows = config.rows();
            const query = search.value.trim().toLocaleLowerCase();
            if (query) rows = rows.filter(row => config.search(row).toLocaleLowerCase().includes(query));
            for (const [key, value] of Object.entries(currentFilters)) {
                if (value) rows = rows.filter(row => String(config.filter(row, key)) === value);
            }
            const pageCount = Math.max(1, Math.ceil(rows.length / pageSize));
            page = Math.min(page, pageCount - 1);
            const start = page * pageSize;
            table.innerHTML = renderTable(rows.slice(start, start + pageSize), config.columns) +
                (rows.length > pageSize ? `<div class="pagination"><span>Showing ${start + 1}–${Math.min(start + pageSize, rows.length)} of ${rows.length}</span><div><button class="button button-outline" data-page="previous" ${page === 0 ? "disabled" : ""}>Previous</button><button class="button button-outline" data-page="next" ${page >= pageCount - 1 ? "disabled" : ""}>Next</button></div></div>` : "");
            table.querySelectorAll("[data-page]").forEach(button => button.addEventListener("click", () => {
                page += button.dataset.page === "next" ? 1 : -1;
                draw();
            }));
        };
        search.addEventListener("input", () => { page = 0; draw(); });
        content.querySelectorAll("[data-filter]").forEach(select => select.addEventListener("change", () => {
            currentFilters[select.dataset.filter] = select.value;
            page = 0;
            draw();
        }));
        draw();
    }

