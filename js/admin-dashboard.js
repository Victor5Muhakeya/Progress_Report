    function formValues() {
        const values = {};
        for (const field of formCatalog[editing.type].fields) {
            const element = form.elements.namedItem(field.key);
            if (field.type === "subject-picker") {
                values[field.key] = JSON.parse(element.value || "[]");
            } else if (element instanceof HTMLSelectElement && element.multiple) {
                values[field.key] = [...element.selectedOptions].map(option =>
                    field.key === "forms" ? Number(option.value) : option.value);
            } else if (element instanceof HTMLInputElement && element.type === "number") {
                values[field.key] = element.value === "" ? "" : Number(element.value);
            } else if (element && (element.value === "true" || element.value === "false")) {
                values[field.key] = element.value === "true";
            } else {
                values[field.key] = element?.value.trim() ?? "";
            }
        }
        return values;
    }

    function validateForm(type, values, editingId) {
        const required = formCatalog[type].fields.filter(field => field.required);
        for (const field of required) {
            if (values[field.key] === "" || values[field.key] === undefined || (Array.isArray(values[field.key]) && !values[field.key].length)) {
                return `${field.label} is required.`;
            }
        }
        if (type === "teacher") {
            if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(values.email)) return "Enter a valid email address.";
            if (data.teachers.some(item => item.id !== editingId && item.email.toLowerCase() === values.email.toLowerCase())) return "A teacher already uses this email address.";
            if (data.teachers.some(item => item.id !== editingId && item.staffId.toLowerCase() === values.staffId.toLowerCase())) return "This staff ID is already in use.";
            const missingAssignedSubjects = data.assignments.filter(assignment =>
                assignment.teacherId === editingId && assignment.active &&
                !values.subjectIds.includes(assignment.subjectId));
            if (missingAssignedSubjects.length) {
                return "This teacher has active class assignments in a subject you are removing. Update or deactivate those assignments first.";
            }
        }
        if (type === "student" && data.students.some(item => item.id !== editingId && item.admissionNumber.toLowerCase() === values.admissionNumber.toLowerCase())) return "This admission number is already in use.";
        if (type === "subject" && data.subjects.some(item => item.id !== editingId && item.code.toLowerCase() === values.code.toLowerCase())) return "This subject code is already in use.";
        if (type === "subject" && data.subjects.some(item => item.id !== editingId && item.name.toLowerCase() === values.name.toLowerCase())) return "A subject with this name already exists.";
        if (type === "class") {
            values.name = `Form ${values.formNumber}${values.stream.toUpperCase()}`;
            if (data.classes.some(item => item.id !== editingId && item.formNumber === Number(values.formNumber) && item.stream.toLowerCase() === values.stream.toLowerCase() && item.yearId === values.yearId)) return "A class with this form, stream, and academic year already exists.";
            values.formNumber = Number(values.formNumber);
            values.stream = values.stream.toUpperCase();
        }
        if (type === "year" && data.years.some(item => item.id !== editingId && item.label.toLowerCase() === values.label.toLowerCase())) return "This academic year already exists.";
        if (type === "term") {
            if (values.startsOn && values.endsOn && values.endsOn < values.startsOn) return "The term end date must be on or after the start date.";
            if (data.years.find(year => year.id === values.yearId)?.terms.some(item => item.id !== editingId && item.name === values.name)) return "This year already has a term with that name.";
        }
        if (type === "assignment") {
            const teacher = byId(data.teachers, values.teacherId);
            if (!teacher?.active) return "Only active teachers can receive assignments.";
            const group = byId(data.classes, values.classId);
            const subject = byId(data.subjects, values.subjectId);
            if (!group?.active || !subject?.active) return "Choose an active class and subject.";
            if (!(teacher.subjectIds || []).includes(values.subjectId)) return "Choose a subject listed on this teacher's profile.";
            if (group.yearId !== values.yearId) return "Choose a class associated with the selected academic year.";
            if (!group || !subject || !subject.forms.includes(Number(group.formNumber))) return "The selected subject is not available for this class form.";
            if (data.assignments.some(item => item.id !== editingId && item.teacherId === values.teacherId && item.classId === values.classId && item.subjectId === values.subjectId && item.yearId === values.yearId)) return "This teacher, class, subject, and year assignment already exists.";
        }
        if (type === "student") {
            const group = byId(data.classes, values.classId);
            if (!group || group.yearId !== values.yearId) return "Choose a class associated with the selected academic year.";
            if (data.students.some(item => item.id !== editingId && item.classId === values.classId && item.yearId === values.yearId && item.admissionNumber === values.admissionNumber)) return "This student already has an assignment in the selected class and year.";
        }
        if (type === "promotion") {
            const student = byId(data.students, editingId);
            const group = byId(data.classes, values.classId);
            const year = byId(data.years, values.yearId);
            if (!student || !group || !year || group.yearId !== year.id) return "Choose a class in the selected academic year.";
            if (year.id === student.yearId) return "Choose a new academic year to preserve the learner's history.";
            if (group.formNumber <= byId(data.classes, student.classId)?.formNumber) return "Promotion must move the student to a higher form.";
        }
        if (type === "mark") {
            if (!Number.isFinite(values.mark) || values.mark < 0 || values.mark > 100) return "Marks must be a number from 0 to 100.";
            const assignment = byId(data.assignments, values.assignmentId);
            const term = termById(values.termId);
            const student = byId(data.students, values.studentId);
            if (!assignment?.active) return "Choose an active teacher assignment.";
            if (!term || term.yearId !== assignment.yearId) return "The selected term must belong to the assignment's academic year.";
            const belongsToAssignment = student && (
                (student.classId === assignment.classId && student.yearId === assignment.yearId) ||
                (student.history || []).some(item => item.classId === assignment.classId && item.yearId === assignment.yearId)
            );
            if (!belongsToAssignment) return "The selected student must belong to the assigned class and academic year.";
            if (!term.open) return "This term is closed. Marks cannot be added or changed.";
            if (data.marks.some(item => {
                if (item.id === editingId || item.studentId !== values.studentId || item.termId !== values.termId) return false;
                const existingAssignment = byId(data.assignments, item.assignmentId);
                return existingAssignment && existingAssignment.subjectId === assignment.subjectId && existingAssignment.yearId === assignment.yearId;
            })) return "A mark already exists for this student, subject, and term.";
        }
        return "";
    }

    function upsert(type, values, id) {
        if (type === "promotion") {
            const student = byId(data.students, id);
            student.history = [...(student.history || []), { classId: student.classId, yearId: student.yearId, movedAt: new Date().toISOString() }];
            student.classId = values.classId;
            student.yearId = values.yearId;
            return;
        }
        const collection = {
            teacher: data.teachers,
            student: data.students,
            class: data.classes,
            subject: data.subjects,
            year: data.years,
            assignment: data.assignments,
            mark: data.marks
        }[type];
        if (type === "term") {
            const existing = id ? allTerms().find(term => term.id === id) : null;
            const year = byId(data.years, values.yearId);
            if (existing && existing.yearId !== values.yearId) {
                const oldYear = byId(data.years, existing.yearId);
                oldYear.terms = oldYear.terms.filter(term => term.id !== id);
            }
            const target = byId(data.years, values.yearId);
            const term = { id: id || window.AdminData.id("term"), name: values.name, startsOn: values.startsOn, endsOn: values.endsOn, open: values.open };
            const index = target.terms.findIndex(item => item.id === term.id);
            if (index >= 0) target.terms[index] = term;
            else target.terms.push(term);
            if (values.open) {
                for (const otherYear of data.years) for (const otherTerm of otherYear.terms) if (otherTerm.id !== term.id) otherTerm.open = false;
            }
            return;
        }
        if (type === "year") {
            const year = { id: id || window.AdminData.id("year"), label: values.label, active: values.active, terms: id ? byId(data.years, id).terms : [] };
            const index = collection.findIndex(item => item.id === id);
            if (index >= 0) collection[index] = year;
            else {
                year.terms = ["Term 1", "Term 2", "Term 3"].map((name, index) => ({
                    id: window.AdminData.id("term"), name, startsOn: "", endsOn: "", open: false
                }));
                collection.push(year);
            }
            if (values.active) {
                collection.forEach(item => { item.active = item.id === year.id; });
                for (const otherYear of collection) for (const term of otherYear.terms) if (otherYear.id !== year.id) term.open = false;
            }
            return;
        }
        const previousStudent = type === "student" && id ? byId(collection, id) : null;
        const item = { ...(byId(collection, id) || {}), ...values, id: id || window.AdminData.id(type) };
        if (type === "class") item.name = `Form ${item.formNumber}${item.stream}`;
        if (type === "student" && previousStudent &&
            (previousStudent.classId !== item.classId || previousStudent.yearId !== item.yearId)) {
            item.history = [...(previousStudent.history || []), { classId: previousStudent.classId, yearId: previousStudent.yearId, movedAt: new Date().toISOString() }];
        }
        const index = collection.findIndex(record => record.id === id);
        if (index >= 0) collection[index] = item;
        else collection.push(item);
        if (type === "mark") item.mark = Number(item.mark);
        if (type === "teacher" && !item.active) data.assignments.filter(assignment => assignment.teacherId === item.id).forEach(assignment => { assignment.active = false; });
        if (type === "class" && !item.active) data.assignments.filter(assignment => assignment.classId === item.id).forEach(assignment => { assignment.active = false; });
        if (type === "subject" && !item.active) data.assignments.filter(assignment => assignment.subjectId === item.id).forEach(assignment => { assignment.active = false; });
    }

    function handleFormSubmit(event) {
        event.preventDefault();
        if (event.submitter?.value !== "save") {
            dialog.close();
            return;
        }
        const values = formValues();
        const error = validateForm(editing.type, values, editing.id);
        if (error) {
            formError.textContent = error;
            return;
        }
        const labels = {
            teacher: "Teacher saved", student: "Student saved", class: "Class saved", subject: "Subject saved",
            year: "Academic year saved", term: "Term saved", assignment: "Teacher assignment saved", mark: "Mark saved", promotion: "Student promoted"
        };
        upsert(editing.type, values, editing.id);
        try {
            notifyChange(editing.type === "promotion" ? labels[editing.type] : editing.id ? `${labels[editing.type]} (updated)` : labels[editing.type],
                `${formCatalog[editing.type].title}: ${Object.values(values).slice(0, 2).join(" · ")}`);
        } catch {
            return;
        }
        dialog.close();
        showToast(editing.id ? "Changes saved" : "Record added");
        render();
    }

