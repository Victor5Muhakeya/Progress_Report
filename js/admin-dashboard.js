    function svgBars(items, options = {}) {
        if (!items.length) return `<div class="empty-state"><strong>No results to chart</strong>Save demonstration marks to see this chart.</div>`;
        const width = 620;
        const height = 220;
        const left = 35;
        const bottom = 43;
        const top = 14;
        const plotHeight = height - top - bottom;
        const step = (width - left - 12) / items.length;
        const lines = [0, 25, 50, 75, 100].map(value => {
            const y = top + plotHeight * (1 - value / 100);
            return `<line x1="${left}" y1="${y}" x2="${width - 8}" y2="${y}" stroke="#e8ede7"/><text x="${left - 7}" y="${y + 3}" text-anchor="end">${value}%</text>`;
        }).join("");
        const bars = items.map((item, index) => {
            const value = Math.max(0, Math.min(100, item.value || 0));
            const barWidth = Math.min(44, step * .55);
            const barHeight = plotHeight * value / 100;
            const x = left + index * step + (step - barWidth) / 2;
            const y = top + plotHeight - barHeight;
            const label = item.label.length > 13 ? `${item.label.slice(0, 12)}…` : item.label;
            return `<g><title>${esc(item.label)}: ${value.toFixed(1)}%</title><rect x="${x}" y="${y}" width="${barWidth}" height="${barHeight}" rx="3" fill="${COLORS[index % COLORS.length]}"/><text x="${x + barWidth / 2}" y="${Math.max(top + 10, y - 5)}" text-anchor="middle">${Math.round(value)}%</text><text x="${x + barWidth / 2}" y="${height - 13}" text-anchor="middle">${esc(label)}</text></g>`;
        }).join("");
        return `<svg class="chart" viewBox="0 0 ${width} ${height}" role="img" aria-label="${esc(options.label || "Bar chart")}">${lines}${bars}</svg>`;
    }

    function donutChart(counts) {
        const total = Object.values(counts).reduce((sum, value) => sum + value, 0);
        if (!total) return `<div class="empty-state"><strong>No marks recorded</strong>Grade distribution will appear here.</div>`;
        let angle = -Math.PI / 2;
        const radius = 72;
        const paths = Object.entries(counts).map(([grade, count], index) => {
            if (!count) return "";
            const next = angle + count / total * Math.PI * 2;
            const startX = 105 + radius * Math.cos(angle);
            const startY = 100 + radius * Math.sin(angle);
            const endX = 105 + radius * Math.cos(next);
            const endY = 100 + radius * Math.sin(next);
            const largeArc = next - angle > Math.PI ? 1 : 0;
            const middleX = 105 + radius * Math.cos(angle + Math.PI);
            const middleY = 100 + radius * Math.sin(angle + Math.PI);
            const arc = count === total
                ? `M ${startX} ${startY} A ${radius} ${radius} 0 0 1 ${middleX} ${middleY} A ${radius} ${radius} 0 0 1 ${startX} ${startY}`
                : `M ${startX} ${startY} A ${radius} ${radius} 0 ${largeArc} 1 ${endX} ${endY}`;
            const path = `<path d="${arc}" fill="none" stroke="${COLORS[index]}" stroke-width="22"><title>${grade}: ${count}</title></path>`;
            angle = next;
            return path;
        }).join("");
        const legend = Object.entries(counts).map(([grade, count], index) =>
            `<span class="legend-item"><i class="legend-swatch" style="background:${COLORS[index]}"></i>${grade} · ${count}</span>`).join("");
        return `<svg class="chart" style="max-width:250px;min-height:180px;margin:auto" viewBox="0 0 210 200" role="img" aria-label="Grade distribution donut chart">${paths}<text x="105" y="98" text-anchor="middle" style="font-size:22px;font-weight:700;fill:#19332f">${total}</text><text x="105" y="116" text-anchor="middle">results</text></svg><div class="chart-legend">${legend}</div>`;
    }

