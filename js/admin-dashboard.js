    function optionsFor(field, selectedValues = []) {
        switch (field.source) {
            case "teachers": return data.teachers.filter(teacher => teacher.active).map(item => [item.id, `${item.fullName} · ${item.staffId}`]);
            case "classes": return data.classes.filter(group => group.active).map(item => [item.id, `${item.name} · ${yearLabel(item.yearId)}`]);
            case "subjects": return data.subjects.filter(subject => subject.active || selectedValues.includes(subject.id)).map(item =>
                [item.id, `${item.name} · ${item.code}${item.active ? "" : " · Inactive"}`]);
            case "teacherSubjects": {
                const teacherId = form.elements.namedItem("teacherId")?.value;
                const teacher = byId(data.teachers, teacherId);
                return data.subjects.filter(subject => subject.active &&
                    (teacher?.subjectIds || []).includes(subject.id)).map(item => [item.id, `${item.name} · ${item.code}`]);
            }
            case "years": return data.years.map(item => [item.id, `${item.label}${item.active ? " · Active" : ""}`]);
            case "students": return data.students.map(item => [item.id, `${item.fullName} · ${item.admissionNumber}`]);
            case "assignments": return data.assignments.filter(item => item.active).map(item =>
                [item.id, `${teacherName(item.teacherId)} · ${className(item.classId)} · ${subjectName(item.subjectId)}`]);
            case "terms": return allTerms().map(item => [item.id, `${item.yearLabel} · ${item.name}${item.open ? "" : " · Closed"}`]);
            default: return [];
        }
    }

